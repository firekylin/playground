export function language() {
    return document.documentElement.lang === 'en-US' ? 'en-US' : 'zh-CN';
}
export function t(value) {
    return language() === 'en-US' ? (english[value] ?? value) : value;
}
const originals = [];
export function translatePage(locale) {
    if (!originals.length) {
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        while (walker.nextNode()) {
            const node = walker.currentNode;
            if (node.parentElement.closest('script, style, textarea, pre, code')) continue;
            if (english[node.textContent.trim()]) originals.push({ node, text: node.textContent });
        }
        for (const node of document.querySelectorAll('[title], [aria-label], [placeholder]')) {
            for (const attr of ['title', 'aria-label', 'placeholder']) {
                if (node.hasAttribute(attr) && english[node.getAttribute(attr)]) {
                    originals.push({ node, attr, text: node.getAttribute(attr) });
                }
            }
        }
    }
    document.documentElement.lang = locale;
    for (const { node, attr, text } of originals) {
        if (!node.isConnected) continue;
        const value =
            locale === 'en-US' ? text.replace(text.trim(), english[text.trim()] ?? text.trim()) : text;
        if (attr) node.setAttribute(attr, value);
        else node.textContent = value;
    }
}
